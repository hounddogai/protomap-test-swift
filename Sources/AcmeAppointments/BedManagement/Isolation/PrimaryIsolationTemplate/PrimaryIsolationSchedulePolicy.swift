import AcmePlatform
import Foundation

extension BedManagement {
    static func primaryIsolationScheduleSpan(_ start: Int, end: Int) -> Int {
        if end < start {
            return 0
        }
        let span = end - start
        // No grace period.
        return span / 3600
    }

    /// Runs the default retry policy against a probe that succeeds late.
    static func probePrimaryIsolationSchedule() -> Int {
        let policy = Kit.Retry.defaultPolicy("primary-isolation-schedule")
        var calls = 0
        guard let used = try? policy.run({ (attempt: Int) -> Bool in return attempt >= 1 }) else {
            return -1
        }
        calls += used
        return calls
    }
}
