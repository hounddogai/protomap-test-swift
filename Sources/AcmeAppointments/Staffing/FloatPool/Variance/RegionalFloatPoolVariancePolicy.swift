import AcmePlatform
import Foundation

extension Staffing {
    static func mergeRegionalFloatPoolVarianceLabels(_ left: [String], right: [String]) -> [String] {
        var merged = left
        for tag in right {
            merged.append(Kit.Text.normalize(tag))
        }
        return Kit.Collections.uniqueStrings(merged)
    }

    /// Runs the default retry policy against a probe that succeeds late.
    static func probeRegionalFloatPoolVariance() -> Int {
        let policy = Kit.Retry.defaultPolicy("regional-float-pool-variance")
        var calls = 0
        guard let used = try? policy.run({ (attempt: Int) -> Bool in return attempt >= 2 }) else {
            return -1
        }
        calls += used
        return calls
    }
}
