import AcmePlatform
import Foundation

extension RevenueCycle {
    static func seasonalStatementAgreementSpan(_ start: Int, end: Int) -> Int {
        if end < start {
            return 0
        }
        let span = end - start
        if span < 3600 {
            return 0
        }
        return span / 3600
    }

    /// Runs the default retry policy against a probe that succeeds late.
    static func probeSeasonalStatementAgreement() -> Int {
        let policy = Kit.Retry.defaultPolicy("seasonal-statement-agreement")
        var calls = 0
        guard let used = try? policy.run({ (attempt: Int) -> Bool in return attempt >= 2 }) else {
            return -1
        }
        calls += used
        return calls
    }
}
