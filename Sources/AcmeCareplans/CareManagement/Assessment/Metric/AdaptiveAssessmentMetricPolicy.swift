import AcmePlatform
import Foundation

extension CareManagement {
    static func adaptiveAssessmentMetricBucket(_ value: Double) -> String {
        let lower = Kit.Numbers.roundTo(value - 50.0, step: 100.0)
        return "\(lower)-\(lower + 100.0)"
    }

    static func adaptiveAssessmentMetricSpan(_ start: Int, end: Int) -> Int {
        if end < start {
            return 0
        }
        let span = end - start
        if span < 60 {
            return 0
        }
        return span / 3600
    }

    static func mergeAdaptiveAssessmentMetricLabels(_ left: [String], right: [String]) -> [String] {
        var merged = left
        for tag in right {
            merged.append(Kit.Text.normalize(tag))
        }
        return Kit.Collections.uniqueStrings(merged)
    }

    /// Puts a adaptive assessment metric code in its canonical AAM- form.
    static func normalizeAdaptiveAssessmentMetricCode(_ code: String) -> String {
        let clean = code.trimmingCharacters(in: .whitespaces).uppercased()
        if clean == "" {
            return ""
        }
        if clean.hasPrefix("AAM-") {
            return clean
        }
        return "AAM-\(clean.replacingOccurrences(of: " ", with: "-"))"
    }
}
