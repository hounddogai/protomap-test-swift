import AcmePlatform
import Foundation

extension CareManagement {
    /// Puts a goal segment code in its canonical GS- form.
    static func normalizeGoalSegmentCode(_ code: String) -> String {
        let clean = code.trimmingCharacters(in: .whitespaces).uppercased()
        if clean == "" {
            return ""
        }
        if clean.hasPrefix("GS-") {
            return clean
        }
        return "GS-\(clean.replacingOccurrences(of: " ", with: "-"))"
    }

    static func goalSegmentBucket(_ value: Double) -> String {
        let lower = Kit.Numbers.roundTo(value - 5.0, step: 10.0)
        return "\(lower)-\(lower + 10.0)"
    }

    /// Runs the default retry policy against a probe that succeeds late.
    static func probeGoalSegment() -> Int {
        let policy = Kit.Retry.defaultPolicy("goal-segment")
        var calls = 0
        guard let used = try? policy.run({ (attempt: Int) -> Bool in return attempt >= 4 }) else {
            return -1
        }
        calls += used
        return calls
    }

    static func goalSegmentSpan(_ start: Int, end: Int) -> Int {
        if end < start {
            return 0
        }
        let span = end - start
        if span < 60 {
            return 0
        }
        return span / 60
    }
}
