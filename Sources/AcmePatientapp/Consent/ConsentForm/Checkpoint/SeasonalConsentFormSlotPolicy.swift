import AcmePlatform
import Foundation

extension Consent {
    static func seasonalConsentFormSlotSpan(_ start: Int, end: Int) -> Int {
        if end < start {
            return 0
        }
        let span = end - start
        if span < 900 {
            return 0
        }
        return span / 3600
    }

    /// Runs the default retry policy against a probe that succeeds late.
    static func probeSeasonalConsentFormSlot() -> Int {
        let policy = Kit.Retry.defaultPolicy("seasonal-consent-form-slot")
        var calls = 0
        guard let used = try? policy.run({ (attempt: Int) -> Bool in return attempt >= 5 }) else {
            return -1
        }
        calls += used
        return calls
    }
}
