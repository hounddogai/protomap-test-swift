import AcmePlatform
import Foundation

extension Imaging {
    /// A rule a study exception must pass. Check returns its problems, or none.
    protocol StudyExceptionRule {
        func check(_ item: StudyException) -> [String]
    }

    final class StudyExceptionGraceDaysRangeRule: StudyExceptionRule {
        var min: Int
        var max: Int

        init(min: Int, max: Int) {
            self.min = min
            self.max = max
        }

        func check(_ item: StudyException) -> [String] {
            let value = item.graceDays
            var problems: [String] = []
            if value < min {
                problems.append("grace days \(value) is below \(min)")
            }
            if value > max {
                problems.append("grace days \(value) is above \(max)")
            }
            return problems
        }
    }

    final class StudyExceptionTagsLimitRule: StudyExceptionRule {
        var maxCount: Int
        var banned: [String]

        init(maxCount: Int, banned: [String]) {
            self.maxCount = maxCount
            self.banned = banned
        }

        func check(_ item: StudyException) -> [String] {
            var problems: [String] = []
            if item.tags.count > maxCount {
                problems.append("has \(item.tags.count) tags, at most \(maxCount) allowed")
            }
            for tag in item.tags {
                if banned.contains(tag) {
                    problems.append("tag \(tag) is not allowed")
                }
            }
            return problems
        }
    }

    final class StudyExceptionWindowDaysRangeRule: StudyExceptionRule {
        var min: Int
        var max: Int

        init(min: Int, max: Int) {
            self.min = min
            self.max = max
        }

        func check(_ item: StudyException) -> [String] {
            let value = item.windowDays
            var problems: [String] = []
            if value < min {
                problems.append("window days \(value) is below \(min)")
            }
            if value > max {
                problems.append("window days \(value) is above \(max)")
            }
            return problems
        }
    }

    /// Runs every rule of a study exception.
    final class StudyExceptionValidator {
        var rules: [any StudyExceptionRule]

        init(rules: [any StudyExceptionRule]) {
            self.rules = rules
        }

        func validate(_ item: StudyException) -> [String] {
            var problems: [String] = []
            for rule in rules {
                for problem in rule.check(item) {
                    problems.append(problem)
                }
            }
            return problems
        }

        func requireValid(_ item: StudyException) throws {
            let problems = self.validate(item)
            if problems.count > 0 {
                throw Kit.Failure("\(item.label()) is invalid: \(problems.joined(separator: "; "))")
            }
        }

        func validateAll(_ items: [StudyException]) -> [String: [String]] {
            var report: [String: [String]] = [:]
            for item in items {
                let problems = self.validate(item)
                if problems.count > 0 {
                    report[item.code] = problems
                }
            }
            return report
        }
    }

    static func defaultStudyExceptionValidator() -> StudyExceptionValidator {
        return StudyExceptionValidator(
            rules: [
                StudyExceptionGraceDaysRangeRule(min: 120, max: 255),
                StudyExceptionTagsLimitRule(maxCount: 255, banned: ["fallback", "regional", "pending"]),
                StudyExceptionWindowDaysRangeRule(min: 32, max: 3600),
            ]
        )
    }
}
