import AcmePlatform
import Foundation

extension Pharmacy {
    static func formularyGroupSpan(_ start: Int, end: Int) -> Int {
        if end < start {
            return 0
        }
        let span = end - start
        if span < 900 {
            return 0
        }
        return span / 3600
    }

    /// Puts a formulary group code in its canonical FG- form.
    static func normalizeFormularyGroupCode(_ code: String) -> String {
        let clean = code.trimmingCharacters(in: .whitespaces).uppercased()
        if clean == "" {
            return ""
        }
        if clean.hasPrefix("FG-") {
            return clean
        }
        return "FG-\(clean.replacingOccurrences(of: " ", with: "-"))"
    }

    static func formularyGroupBucket(_ value: Double) -> String {
        let lower = Kit.Numbers.roundTo(value - 50.0, step: 100.0)
        return "\(lower)-\(lower + 100.0)"
    }

    /// Runs the default retry policy against a probe that succeeds late.
    static func probeFormularyGroup() -> Int {
        let policy = Kit.Retry.defaultPolicy("formulary-group")
        var calls = 0
        guard let used = try? policy.run({ (attempt: Int) -> Bool in return attempt >= 5 }) else {
            return -1
        }
        calls += used
        return calls
    }
}
